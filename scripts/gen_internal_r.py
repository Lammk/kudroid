#!/usr/bin/env python3
"""Generate framework/com/android/internal/R.java: the framework's own attr ids and styleable arrays.

Input : <aosp>/core/res/res/values/{attrs.xml,public.xml}  (AOSP android-10.0.0_r47, Apache-2.0)
Output: com.android.internal.R.styleable with, for each requested <declare-styleable>, the
        int[] of its attribute ids (sorted by id, as aapt emits them) and one index constant
        per attribute (<Styleable>_<attr>), exactly the shape framework code such as
        View(Context, AttributeSet, int, int) reads through obtainStyledAttributes.
Only attributes that have a public id are included; the others cannot appear in an app's
compiled XML and have no stable id here.
Stdlib only, deterministic.
"""
import argparse
import os
import sys
import xml.etree.ElementTree as ET

TAG = "android-10.0.0_r47"

STYLEABLES = [
    "Theme", "Window", "View", "ViewTag", "Include", "ViewGroup", "ViewStub",
    "ViewGroup_Layout", "ViewGroup_MarginLayout", "FrameLayout", "FrameLayout_Layout",
    "LinearLayout", "LinearLayout_Layout", "RelativeLayout", "RelativeLayout_Layout",
    "TextView", "TextAppearance", "ImageView", "ProgressBar", "CompoundButton", "ScrollView",
    "ViewDrawableStates", "DrawableStates", "Drawable", "DrawableWrapper", "DrawableCorners",
    "StateListDrawable", "StateListDrawableItem", "ColorDrawable", "BitmapDrawable",
    "NinePatchDrawable", "ShapeDrawable", "GradientDrawable", "GradientDrawableSize",
    "GradientDrawableGradient", "GradientDrawableSolid", "GradientDrawableStroke",
    "GradientDrawablePadding", "InsetDrawable", "ClipDrawable", "ScaleDrawable", "RotateDrawable",
    "LayerDrawable", "LayerDrawableItem", "RippleDrawable", "AnimatedStateListDrawableItem",
    "AnimatedStateListDrawableTransition",
    "AccelerateInterpolator", "DecelerateInterpolator", "CycleInterpolator",
    "AnticipateInterpolator", "OvershootInterpolator", "AnticipateOvershootInterpolator",
    "PathInterpolator",
    "Animator", "PropertyValuesHolder", "Keyframe", "AnimatorSet", "PropertyAnimator",
    "Animation", "AnimationSet", "TranslateAnimation", "RotateAnimation", "ScaleAnimation",
    "AlphaAnimation", "LayoutAnimation", "GridLayoutAnimation",
]


def read_public_attrs(path):
    root = ET.parse(path).getroot()
    ids = {}
    for el in root:
        if el.tag == "public" and el.attrib.get("type") == "attr":
            ids[el.attrib["name"]] = int(el.attrib["id"], 16)
    return ids


def read_styleables(path):
    root = ET.parse(path).getroot()
    result = {}
    for el in root.iter("declare-styleable"):
        name = el.attrib["name"]
        attrs = [a.attrib["name"] for a in el if a.tag == "attr" and "name" in a.attrib]
        result.setdefault(name, attrs)
    return result


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.dirname(here)
    ap = argparse.ArgumentParser()
    ap.add_argument("--aosp", default=os.path.join(
        root, "third_party/aosp/platform_frameworks_base/core/res/res"))
    ap.add_argument("--out", default=os.path.join(root, "framework/com/android/internal/R.java"))
    args = ap.parse_args()

    public = read_public_attrs(os.path.join(args.aosp, "values/public.xml"))
    declared = read_styleables(os.path.join(args.aosp, "values/attrs.xml"))

    out = []
    w = out.append
    w("/*")
    w(" * Generated by scripts/gen_internal_r.py -- do not edit.")
    w(" * Derived from AOSP %s frameworks/base/core/res/res/values (attrs.xml, public.xml)." % TAG)
    w(" * Copyright (C) 2006 The Android Open Source Project")
    w(" *")
    w(" * Licensed under the Apache License, Version 2.0 (the \"License\");")
    w(" * you may not use this file except in compliance with the License.")
    w(" * You may obtain a copy of the License at")
    w(" *")
    w(" *      http://www.apache.org/licenses/LICENSE-2.0")
    w(" *")
    w(" * Unless required by applicable law or agreed to in writing, software")
    w(" * distributed under the License is distributed on an \"AS IS\" BASIS,")
    w(" * WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.")
    w(" * See the License for the specific language governing permissions and")
    w(" * limitations under the License.")
    w(" */")
    w("package com.android.internal;")
    w("")
    w("/** The framework's styleable index tables (public attributes only). */")
    w("public final class R {")
    w("    private R() {}")
    w("")
    w("    public static final class attr {")
    w("        private attr() {}")
    for attr_name, rid in sorted(public.items(), key=lambda kv: (kv[1], kv[0])):
        if attr_name.isidentifier():
            w("        public static final int %s = 0x%08x;" % (attr_name, rid))
    w("    }")
    w("")
    w("    public static final class styleable {")
    w("        private styleable() {}")
    for name in STYLEABLES:
        if name not in declared:
            sys.exit("styleable %s not found in attrs.xml" % name)
        pairs = sorted({(public[a], a) for a in declared[name] if a in public})
        w("")
        w("        public static final int[] %s = {" % name)
        for rid, attr in pairs:
            w("            0x%08x,  // %s" % (rid, attr))
        w("        };")
        for index, (rid, attr) in enumerate(pairs):
            w("        public static final int %s_%s = %d;" % (name, attr, index))
    w("    }")
    w("}")
    w("")
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print("wrote %s (%d styleables)" % (args.out, len(STYLEABLES)))


if __name__ == "__main__":
    main()
